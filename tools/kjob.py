"""Run a sweep on Kaggle's free CPU kernels instead of this laptop.

Our bottleneck is CPU-hours: one 32-seed sweep row is 64 episodes x 720 steps.
A Kaggle kernel is 4 free vCPUs for up to 12 hours and several can run at once,
so the queue moves in parallel with local work and costs nothing.

The repo travels inside the script as a base64 tarball -- no dataset to publish,
no internet needed at run time (kaggle-environments ships in the Kaggle image).

    python tools/kjob.py push t-w30,t-w32 --games 32 --name wheat-count
    python tools/kjob.py status wheat-count
    python tools/kjob.py logs wheat-count      # prints only the result rows

`push` prints the slug; `status`/`logs` take the same name. Kaggle keeps one
kernel per slug, so pushing the same name again replaces and re-runs it.
"""
import argparse
import base64
import io
import json
import re
import subprocess
import sys
import tarfile
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
KAGGLE = "C:/Users/livde/AppData/Roaming/Python/Python314/Scripts/kaggle.exe"
# Everything a sweep needs and nothing else: the payload is inlined into the
# script, so bench/ as a whole (mined traces included) would blow the size up.
PAYLOAD = ["main.py", "tools/eval.py", "tools/sweep.py", "tools/thrash.py",
           "tools/anneal.py", "tools/record.py", "tools/bake.py", "tools/plan.py"]
BENCH = ["v3.py", "v14.py", "v15.py", "v16.py", "v17.py"] + [
    f"ref_{name}.py" for name in
    ("fallow_finn", "wheat_walter", "rotation_rosa", "homestead_hana", "melon_mateo",
     "rancher_rita", "broker_bea", "ledger_lena", "slotter_silas", "closer_cleo")]

SCRIPT = '''"""Generated by tools/kjob.py -- do not edit here."""
import base64, io, os, shutil, subprocess, sys, tarfile, traceback

OUT = "/kaggle/working/result.txt"


def report(text):
    print(text, flush=True)
    with open(OUT, "a", encoding="utf-8") as fh:
        fh.write(text + chr(10))


PAYLOAD = "{payload}"
try:
    os.makedirs("/kaggle/working/repo", exist_ok=True)
    with tarfile.open(fileobj=io.BytesIO(base64.b64decode(PAYLOAD))) as tar:
        tar.extractall("/kaggle/working/repo", filter="data")
    os.chdir("/kaggle/working/repo")
    report("unpacked: " + ", ".join(sorted(os.listdir("."))))
    # The Kaggle image ships kaggle-environments 1.29.3, where a COW costs $600
    # against the $400 the competition actually scores (docs/GAME_SPEC.md), so a
    # kernel on the stock image measures a different game. Pin the version the
    # ladder uses. Overwriting the installed module instead does NOT work: the
    # image imports kaggle_environments before this script runs.
    subprocess.run([sys.executable, "-m", "pip", "install", "-q", "--no-deps",
                    "kaggle-environments=={version}"], check=True)
    fingerprint = subprocess.run(
        [sys.executable, "-c",
         "import importlib.metadata as md;"
         "from kaggle_environments.envs.kaggriculture import kaggriculture as K;"
         "print(md.version('kaggle-environments'), K.ANIMALS['COW']['cost'],"
         "      K.CROPS['STRAWBERRY']['seed'])"],
        capture_output=True, text=True)
    report("env fingerprint: " + fingerprint.stdout.strip() + fingerprint.stderr[-200:])
    assert fingerprint.stdout.split()[1] == "400", "wrong env: COW cost is not 400"
    RUN = {run!r}
    commands = ([RUN] if RUN else
                ["tools/sweep.py {configs} --opp " + opp + " --games {games}"
                 for opp in "{opp}".split(",")])
    for command in commands:
        report("=== " + command)
        completed = subprocess.run([sys.executable] + command.split(),
                                   capture_output=True, text=True)
        report(completed.stdout.strip()[-6000:])
        if completed.returncode:
            bad = [ln for ln in completed.stderr.splitlines()
                   if "Error" in ln or "error" in ln or "Traceback" in ln
                   or ln.startswith("  File")]
            report("STDERR:" + chr(10) + chr(10).join(bad[-25:]))
    # Anything the job wrote under build/ comes home in the kernel output.
    if os.path.isdir("build"):
        for name in os.listdir("build"):
            shutil.copy(os.path.join("build", name), "/kaggle/working/" + name)
except Exception:
    report("KJOB FAILED" + chr(10) + traceback.format_exc())
'''


def _user():
    # ~/.kaggle/access_token is an opaque token, not JSON, so ask the API object --
    # it is the only place the username is resolved for this auth style.
    import kaggle
    api = kaggle.KaggleApi()
    api.authenticate()
    return api.get_config_value("username")


def _sweep_configs():
    sys.path.insert(0, str(ROOT / "tools"))
    import sweep
    return sweep.CONFIGS


ENV_DIR = Path("C:/Users/livde/AppData/Roaming/Python/Python314/site-packages/"
               "kaggle_environments/envs/kaggriculture")


def _env_version():
    import importlib.metadata as md
    return md.version("kaggle-environments")


def _payload():
    buf = io.BytesIO()
    with tarfile.open(fileobj=buf, mode="w:gz") as tar:
        for rel in PAYLOAD:
            tar.add(ROOT / rel, arcname=rel)
        # The Kaggle image ships kaggle-environments 1.29.3, where a COW costs $600
        # against $400 in the 1.32.6 rules the competition actually scores (see
        # docs/GAME_SPEC.md). Kernels have no internet, so carry the env module and
        # overwrite the installed one at run time.
        for name in ("kaggriculture.py", "kaggriculture.json"):
            tar.add(ENV_DIR / name, arcname=f"envsrc/{name}")
        for name in BENCH:
            path = ROOT / "bench" / name
            if path.exists():
                tar.add(path, arcname=f"bench/{name}")
    return base64.b64encode(buf.getvalue()).decode()


def push(args):
    user = _user()
    slug = f"{user}/{args.name}"
    script = SCRIPT.format(payload=_payload(), configs=args.configs,
                           opp=args.opp, games=args.games, version=_env_version(),
                           run=args.run)
    # A generated script with a syntax error runs, dies, and still reports
    # KernelWorkerStatus.COMPLETE with an empty output list -- indistinguishable from
    # a job that produced nothing. Version 1 of this kernel was exactly that. Never
    # push code that has not been compiled here first.
    compile(script, f"{args.name}.py", "exec")
    unknown = [] if args.run else [c for c in args.configs.split(",")
                                   if c not in _sweep_configs()]
    if unknown:
        raise SystemExit(f"unknown sweep config(s): {', '.join(unknown)}")
    with tempfile.TemporaryDirectory() as tmp:
        folder = Path(tmp)
        (folder / f"{args.name}.py").write_text(script, encoding="utf-8")
        (folder / "kernel-metadata.json").write_text(json.dumps({
            "id": slug, "title": args.name, "code_file": f"{args.name}.py",
            "language": "python", "kernel_type": "script",
            "is_private": True, "enable_gpu": False, "enable_internet": True,
            "dataset_sources": [], "competition_sources": [], "kernel_sources": [],
        }, indent=2), encoding="utf-8")
        print(f"payload {len(script) // 1024} KB -> {slug}")
        subprocess.run([KAGGLE, "kernels", "push", "-p", str(folder)], check=True)


def status(args):
    subprocess.run([KAGGLE, "kernels", "status", f"{_user()}/{args.name}"], check=True)


def logs(args):
    # One directory per slug. A shared one silently serves the PREVIOUS kernel's
    # result.txt when a download fails, which is how the canary run reported the
    # panel's numbers back.
    dest = ROOT / ".lab" / "kaggle" / args.name
    dest.mkdir(parents=True, exist_ok=True)
    completed = subprocess.run([KAGGLE, "kernels", "output", f"{_user()}/{args.name}",
                                "-p", str(dest)], capture_output=True, text=True)
    out = dest / "result.txt"
    if out.exists():
        print(out.read_text(encoding="utf-8").strip())
    else:
        # No output yet: fall back to the run log, keeping only the rows that matter.
        log = subprocess.run([KAGGLE, "kernels", "logs", f"{_user()}/{args.name}"],
                             capture_output=True, text=True).stdout
        rows = [ln for ln in log.splitlines() if re.search(r"\d+W-\d+L|Error|Traceback", ln)]
        print("\n".join(rows[-20:]) or completed.stdout or "(no output yet)")


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("push")
    p.add_argument("configs", nargs="?", default="BASE",
                   help="comma-separated sweep config names")
    p.add_argument("--name", default="kaggri-sweep", help="kernel slug (reused on re-push)")
    p.add_argument("--opp", default="main.py", help="one opponent, or a comma-separated panel")
    p.add_argument("--games", type=int, default=16)
    p.add_argument("--run", default="",
                   help="run this command instead of a sweep, e.g. \"tools/anneal.py --budget 400\"")
    p.set_defaults(func=push)
    for name, fn in (("status", status), ("logs", logs)):
        s = sub.add_parser(name)
        s.add_argument("name", nargs="?", default="kaggri-sweep")
        s.set_defaults(func=fn)
    args = ap.parse_args()
    return args.func(args) or 0


if __name__ == "__main__":
    raise SystemExit(main())
