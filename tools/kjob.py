"""Run a sweep on Kaggle's free CPU kernels instead of this laptop.

Our bottleneck is CPU-hours: one 32-seed sweep row is 64 episodes x 720 steps.
A Kaggle kernel is 4 free vCPUs for up to 12 hours and several can run at once,
so the queue moves in parallel with local work and costs nothing.

The repo travels inside the script as a base64 tarball -- no dataset to publish,
no internet needed at run time (kaggle-environments ships in the Kaggle image).

    python tools/kjob.py push t-w30,t-w32 --games 32 --name wheat-count
    python tools/kjob.py status wheat-count
    python tools/kjob.py logs wheat-count      # prints only the result rows

`push` prints the slug; `status`/`logs` take the same name. Kaggle keeps one
kernel per slug, so pushing the same name again replaces and re-runs it.
"""
import argparse
import base64
import io
import json
import re
import subprocess
import sys
import tarfile
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
KAGGLE = "C:/Users/livde/AppData/Roaming/Python/Python314/Scripts/kaggle.exe"
# Everything a sweep needs and nothing else: the payload is inlined into the
# script, so bench/ as a whole (mined traces included) would blow the size up.
PAYLOAD = ["main.py", "tools/eval.py", "tools/sweep.py", "tools/thrash.py"]
BENCH = ["v3.py", "v14.py", "v15.py", "v16.py", "v17.py",
         "ref_broker_bea.py", "ref_closer_cleo.py"]

SCRIPT = '''"""Generated by tools/kjob.py -- do not edit here."""
import base64, io, os, subprocess, sys, tarfile

PAYLOAD = "{payload}"
os.makedirs("/kaggle/working/repo", exist_ok=True)
with tarfile.open(fileobj=io.BytesIO(base64.b64decode(PAYLOAD))) as tar:
    tar.extractall("/kaggle/working/repo")
os.chdir("/kaggle/working/repo")
sys.argv = ["sweep.py"]
print("kaggle-environments:", __import__("kaggle_environments").__version__, flush=True)
completed = subprocess.run(
    [sys.executable, "tools/sweep.py", "{configs}", "--opp", "{opp}", "--games", "{games}"],
    capture_output=True, text=True)
print(completed.stdout)
print(completed.stderr[-4000:], file=sys.stderr)
with open("/kaggle/working/result.txt", "w", encoding="utf-8") as fh:
    fh.write(completed.stdout)
'''


def _user():
    # ~/.kaggle/access_token is an opaque token, not JSON, so ask the API object --
    # it is the only place the username is resolved for this auth style.
    import kaggle
    api = kaggle.KaggleApi()
    api.authenticate()
    return api.get_config_value("username")


def _payload():
    buf = io.BytesIO()
    with tarfile.open(fileobj=buf, mode="w:gz") as tar:
        for rel in PAYLOAD:
            tar.add(ROOT / rel, arcname=rel)
        for name in BENCH:
            path = ROOT / "bench" / name
            if path.exists():
                tar.add(path, arcname=f"bench/{name}")
    return base64.b64encode(buf.getvalue()).decode()


def push(args):
    user = _user()
    slug = f"{user}/{args.name}"
    script = SCRIPT.format(payload=_payload(), configs=args.configs,
                           opp=args.opp, games=args.games)
    with tempfile.TemporaryDirectory() as tmp:
        folder = Path(tmp)
        (folder / f"{args.name}.py").write_text(script, encoding="utf-8")
        (folder / "kernel-metadata.json").write_text(json.dumps({
            "id": slug, "title": args.name, "code_file": f"{args.name}.py",
            "language": "python", "kernel_type": "script",
            "is_private": True, "enable_gpu": False, "enable_internet": False,
            "dataset_sources": [], "competition_sources": [], "kernel_sources": [],
        }, indent=2), encoding="utf-8")
        print(f"payload {len(script) // 1024} KB -> {slug}")
        subprocess.run([KAGGLE, "kernels", "push", "-p", str(folder)], check=True)


def status(args):
    subprocess.run([KAGGLE, "kernels", "status", f"{_user()}/{args.name}"], check=True)


def logs(args):
    completed = subprocess.run([KAGGLE, "kernels", "output", f"{_user()}/{args.name}",
                                "-p", str(ROOT / ".lab" / "kaggle")],
                               capture_output=True, text=True)
    out = ROOT / ".lab" / "kaggle" / "result.txt"
    if out.exists():
        print(out.read_text(encoding="utf-8").strip())
    else:
        # No output yet: fall back to the run log, keeping only the rows that matter.
        log = subprocess.run([KAGGLE, "kernels", "logs", f"{_user()}/{args.name}"],
                             capture_output=True, text=True).stdout
        rows = [ln for ln in log.splitlines() if re.search(r"\d+W-\d+L|Error|Traceback", ln)]
        print("\n".join(rows[-20:]) or completed.stdout or "(no output yet)")


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("push")
    p.add_argument("configs", help="comma-separated sweep config names")
    p.add_argument("--name", default="kaggri-sweep", help="kernel slug (reused on re-push)")
    p.add_argument("--opp", default="main.py")
    p.add_argument("--games", type=int, default=16)
    p.set_defaults(func=push)
    for name, fn in (("status", status), ("logs", logs)):
        s = sub.add_parser(name)
        s.add_argument("name", nargs="?", default="kaggri-sweep")
        s.set_defaults(func=fn)
    args = ap.parse_args()
    return args.func(args) or 0


if __name__ == "__main__":
    raise SystemExit(main())
